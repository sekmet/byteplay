func isolatedTorrentConfig(dir string, seed bool) *torrent.ClientConfig {
	cfg := torrent.NewDefaultClientConfig()
	cfg.DataDir = dir
	cfg.ListenHost = func(string) string { return "127.0.0.1" }
	cfg.ListenPort = 0
	cfg.Seed = seed
	cfg.NoDHT = true
	cfg.DisableTrackers = true
	cfg.DisableIPv6 = true
	cfg.DisableUTP = true
	cfg.NoDefaultPortForwarding = true
	return cfg
}

func TestSeededMediaSourceRangeBeforeFullDownload(t *testing.T) {
	root := os.Getenv("BYTEPLAY_TEST_FIXTURE_ROOT")
	if root == "" {
		t.Skip("requires local generated BYTEPLAY_TEST_FIXTURE_ROOT")
	}
	original, err := os.ReadFile(filepath.Join(root, "clip.mp4"))
	if err != nil || len(original) < 8192 {
		t.Fatalf("missing synthetic 60s clip: %v", err)
	}

	info := metainfo.Info{PieceLength: 256 << 10}
	if err := info.BuildFromFilePath(root); err != nil {
		t.Fatalf("generate torrent metadata: %v", err)
	}
	infoBytes, err := bencode.Marshal(info)
	if err != nil {
		t.Fatal(err)
	}
	mi := &metainfo.MetaInfo{InfoBytes: infoBytes}
	seeder, err := torrent.NewClient(isolatedTorrentConfig(filepath.Dir(root), true))
	if err != nil {
		t.Fatal(err)
	}
	defer seeder.Close()
	seedTorrent, err := seeder.AddTorrent(mi)
	if err != nil {
		t.Fatal(err)
	}
	select {
	case <-seedTorrent.Complete().On():
	case <-time.After(30 * time.Second):
		t.Fatal("local synthetic seed never verified pieces")
	}

	for _, mbps := range []int{20, 100} {
		t.Run(fmt.Sprintf("%dMbps", mbps), func(t *testing.T) {
			// Every attempt has a fresh leecher/client and private temporary
			// files. Retry once ONLY when the actual HTTP range read times out
			// because a loopback peer did not deliver any bytes. Incorrect
			// bytes, HTTP status or progress metrics always fail immediately.
			attemptRange := func(attempt int) (retry bool) {
				cfg := isolatedTorrentConfig(t.TempDir(), false)
				cfg.DownloadRateLimiter = rate.NewLimiter(rate.Limit(mbps*1000000/8), 256<<10)
				leecher, err := torrent.NewClient(cfg)
				if err != nil {
					t.Fatal(err)
				}
				defer leecher.Close()
				download, err := leecher.AddTorrent(mi)
				if err != nil {
					t.Fatal(err)
				}
				download.AddClientPeer(seeder)
				fileIndex := -1
				for i, file := range download.Files() {
					if filepath.Base(file.DisplayPath()) == "clip.mp4" {
						fileIndex = i
						break
					}
				}
				if fileIndex == -1 {
					t.Fatal("clip.mp4 absent from torrent files")
				}
				source, err := newMediaSource(download, fileIndex)
				if err != nil {
					t.Fatal(err)
				}
				ctx, cancel := context.WithTimeout(context.Background(), 25*time.Second)
				defer cancel()
				reconnectDone := make(chan struct{})
				go func() {
					defer close(reconnectDone)
					ticker := time.NewTicker(500 * time.Millisecond)
					defer ticker.Stop()
					for {
						select {
						case <-ctx.Done():
							return
						case <-ticker.C:
							if download.Stats().ActivePeers == 0 {
								download.AddClientPeer(seeder)
							}
						}
					}
				}()
				defer func() { cancel(); <-reconnectDone }()
				reader := source.Open(ctx)
				defer reader.Close()
				req := httptest.NewRequest(http.MethodGet, "/range", nil).WithContext(ctx)
				req.Header.Set("Range", "bytes=1024-8191")
				recorder := httptest.NewRecorder()
				http.ServeContent(recorder, req, "clip.mp4", time.Time{}, reader)
				if recorder.Code != http.StatusPartialContent ||
					!bytes.Equal(recorder.Body.Bytes(), original[1024:8192]) {
					if ctx.Err() == context.DeadlineExceeded && attempt == 1 {
						t.Logf("retrying local-only stalled peer after deadline: mbps=%d peers=%d response=%d bytes=%d",
							mbps, download.Stats().ActivePeers, recorder.Code, recorder.Body.Len())
						return true
					}
					t.Fatalf("local seeded range mismatch: mbps=%d attempt=%d response=%d bytes=%d peers=%d context=%v",
						mbps, attempt, recorder.Code, recorder.Body.Len(), download.Stats().ActivePeers, ctx.Err())
				}
				progress := reader.Progress()
				if progress.FirstByteLatencyMillis == nil || progress.BytesServed < 7168 {
					t.Fatalf("missing observed first-byte/bytes-served metrics: %+v", progress)
				}
				t.Logf("local_source_mbps=%d first_byte_ms=%d bytes_served=%d selected_completed=%d torrent_completed=%d total=%d",
					mbps, *progress.FirstByteLatencyMillis, progress.BytesServed,
					progress.FileBytesCompleted, progress.TorrentBytesCompleted, progress.TorrentBytesTotal)
				if progress.FileBytesCompleted < 8192 || progress.FileBytesCompleted >= progress.FileBytesTotal {
					t.Fatalf("selected file must be partially downloaded after range read: %+v", progress)
				}
				if progress.TorrentBytesTotal <= int64(len(original)) || progress.TorrentBytesCompleted >= progress.TorrentBytesTotal {
					t.Fatalf("range required the full torrent download: %+v", progress)
				}
				return false
			}
			for attempt := 1; attempt <= 2; attempt++ {
				if !attemptRange(attempt) {
					return
				}
			}
			t.Fatal("both isolated local peers timed out before serving the verified range")
		})
	}
}
